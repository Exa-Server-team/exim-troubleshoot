# SECTION 6 — MSP / IP REPUTATION / RBL SCAN
# =============================================================================
hdr "6. MSP / IP Reputation / RBL Scan"
sep

if [[ "$WITH_MSP" -ne 1 ]]; then
  warn "MSP scan skipped by default. Run with --with-msp to enable."
  add_result "INFO" "MSP/RBL scan" "MSP/RBL scan was skipped by default." "Run with --with-msp when reputation or spam-source analysis is required."
else
  if ! cmd_exists curl; then
    fail "curl not found; cannot download MSP"
    add_result "WARN" "MSP/RBL scan" "curl is unavailable, so MSP could not be downloaded." "Install curl or run MSP manually from a trusted source."
  elif [[ ! -x /usr/local/cpanel/3rdparty/bin/perl && ! $(command -v perl 2>/dev/null) ]]; then
    fail "perl not found; cannot run MSP"
    add_result "WARN" "MSP/RBL scan" "Perl is unavailable, so MSP could not be executed." "Install Perl or use cPanel bundled Perl if available."
  else
    CPANEL_PERL="/usr/local/cpanel/3rdparty/bin/perl"
    [[ -x "$CPANEL_PERL" ]] || CPANEL_PERL="$(command -v perl)"
    MSP_URL="https://raw.githubusercontent.com/CpanelInc/tech-MSP/master/msp.pl"
    MSP_TMP="$TMP_DIR/msp.pl"

    info "Downloading MSP from: $MSP_URL"
    if curl -s --max-time 30 "$MSP_URL" -o "$MSP_TMP" && [[ -s "$MSP_TMP" ]]; then
      pass "MSP downloaded"
      echo ""
      info "Running MSP --rbl all. Full output is recorded in technical log."
      MSP_RBL_OUT="$TMP_DIR/msp_rbl.out"
      "$CPANEL_PERL" "$MSP_TMP" --rbl all > "$MSP_RBL_OUT" 2>&1 || true
      sed 's/^/    /' "$MSP_RBL_OUT" | head -200

      if grep -Eiq 'listed|blacklist|rbl.*yes|found.*on' "$MSP_RBL_OUT"; then
        warn "MSP RBL output may indicate one or more reputation concerns"
        add_result "WARN" "MSP RBL scan" "MSP RBL scan completed and may indicate one or more listing/reputation concerns." "Engineer should review the technical log and verify affected IPs with external RBL tools."
        add_summary_note "MSP RBL scan may indicate reputation concerns."
      else
        pass "No obvious RBL listing pattern detected in MSP output"
        add_result "PASS" "MSP RBL scan" "MSP RBL scan completed and no obvious listing pattern was detected in script output." "No action required, but external reputation tools may still be checked for confirmation."
      fi

      echo ""
      info "Running MSP --auth. Full output is recorded in technical log."
      MSP_AUTH_OUT="$TMP_DIR/msp_auth.out"
      "$CPANEL_PERL" "$MSP_TMP" --auth > "$MSP_AUTH_OUT" 2>&1 || true
      sed 's/^/    /' "$MSP_AUTH_OUT" | head -200

      if grep -Eiq 'suspicious|compromised|auth|sent|login|password' "$MSP_AUTH_OUT"; then
        add_result "INFO" "MSP auth scan" "MSP authentication/source scan completed and output was captured for engineer review." "Engineer should review top authenticated senders and confirm whether any account shows abnormal sending behavior."
      else
        add_result "INFO" "MSP auth scan" "MSP authentication/source scan completed with limited or no notable output." "No immediate action required unless queue/log evidence indicates spam."
      fi

      add_engineer_note "MSP --rbl all output saved in technical log. MSP --auth output saved in technical log."
    else
      fail "Failed to download MSP"
      add_result "WARN" "MSP/RBL scan" "MSP could not be downloaded from GitHub." "Engineer should verify internet/GitHub access or run MSP manually."
    fi
  fi
fi

